/* Sumi Icons build: reads icons/*.svg masters and emits the typed factory
   at apps/web/src/ui/icons.ts. Zero dependencies; deterministic output.
   Run: node packages/tokens/build-icons.mjs (or `npm run build -w @poxy/tokens`). */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = join(here, 'icons');
const outFile = join(here, '..', '..', 'apps', 'web', 'src', 'ui', 'icons.ts');

const files = readdirSync(srcDir)
  .filter((f) => f.endsWith('.svg'))
  .sort();

const entries = files.map((file) => {
  const name = file.replace(/\.svg$/, '');
  const raw = readFileSync(join(srcDir, file), 'utf8');
  // Strip comments and collapse whitespace: the app inlines these strings.
  const compact = raw
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\r?\n\s*/g, ' ')
    .replace(/>\s+</g, '><')
    .trim();
  return { name, compact };
});

const names = entries.map((e) => `  | '${e.name}'`).join('\n');
const records = entries
  .map((e) => `  '${e.name}': ${JSON.stringify(e.compact)},`)
  .join('\n');

const out = `/* AUTO-GENERATED by packages/tokens/build-icons.mjs — DO NOT EDIT.
   Sumi Icons: one geometry (grid 24, live 20, stroke 1.5 round,
   currentColor; the star is the only fill). Masters live in
   packages/tokens/icons/. Law: docs/10-BRAND.md §Iconography. */

export type IconName =
${names};

export const ICONS: Record<IconName, string> = {
${records}
};

const parser = new DOMParser();

/** Builds an inline SVG element for an icon. currentColor throughout;
    size in CSS pixels (default 24 — the native grid). */
export function Icon(name: IconName, size = 24): SVGSVGElement {
  const doc = parser.parseFromString(ICONS[name], 'image/svg+xml');
  const svg = doc.documentElement as unknown as SVGSVGElement;
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  return document.importNode(svg, true);
}

/** Raw markup accessor for components that inline via svgFromString. */
export function iconMarkup(name: IconName): string {
  return ICONS[name];
}
`;

writeFileSync(outFile, out, 'utf8');
console.log(`icons.ts: ${entries.length} icons -> ${outFile}`);
