// Generates css/variables.css from tokens.json. Zero dependencies.
// Run: node packages/tokens/build.mjs  (from repo root or package dir)
// The output is committed; CI/review verifies it is reproducible.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(fs.readFileSync(path.join(here, 'tokens.json'), 'utf8'));

const L = [];
const push = (s = '') => L.push(s);

function hexToRgb(hex) {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(', ');
}

push('/* GENERATED by packages/tokens/build.mjs from tokens.json — do not hand-edit.');
push(`   Authority: ${tokens.$meta.authority}`);
push('');
push(`   QUARANTINE: ${tokens.$meta.quarantine} */`);
push('');
push(':root {');

push('  /* color.core (locked) */');
for (const [name, hex] of Object.entries(tokens.color.core)) {
  push(`  --px-${name}: ${hex};`);
}
push('');
push('  /* color.pigment — rarity pigments. QUARANTINE: gems, badges, reveal glow ONLY. */');
for (const [name, p] of Object.entries(tokens.color.pigment)) {
  push(`  --px-pigment-${name}: ${p.hex}; /* ${p.pigment} ${p.kanji} */`);
}
push('');
push('  /* pigment glow variants (alpha 40%) — reveal use only */');
for (const [name, p] of Object.entries(tokens.color.pigment)) {
  push(`  --px-pigment-${name}-glow: rgba(${hexToRgb(p.hex)}, 0.4);`);
}
push('');
push('  /* color.functional — system feedback at caption sizes only */');
for (const [name, hex] of Object.entries(tokens.color.functional)) {
  push(`  --px-${name}: ${hex};`);
}
push('');
push('  /* space (8pt base, 4 for icon padding) */');
for (const [name, v] of Object.entries(tokens.space)) {
  push(`  --px-space-${name}: ${v};`);
}
push('');
push('  /* radius */');
for (const [name, v] of Object.entries(tokens.radius)) {
  push(`  --px-radius-${name}: ${v};`);
}
push('');
push('  /* type families */');
for (const [name, v] of Object.entries(tokens.type.families)) {
  push(`  --px-font-${name}: ${v};`);
}
push('');
push('  /* type roles: family / size / line / weight / tracking */');
for (const [role, t] of Object.entries(tokens.type.roles)) {
  push(`  --px-type-${role}-family: var(--px-font-${t.family});`);
  push(`  --px-type-${role}-size: ${t.size};`);
  push(`  --px-type-${role}-line: ${t.line};`);
  push(`  --px-type-${role}-weight: ${t.weight};`);
  push(`  --px-type-${role}-tracking: ${t.tracking};`);
}
push('');
push('  /* motion — three tempos only (Codex §7). Ritual durations are');
push('     choreographed per-beat in ui/motion; only the ease lives here. */');
for (const [name, v] of Object.entries(tokens.motion)) {
  push(`  --px-${name}: ${v};`);
}
push('');
push('  /* layout — tatami */');
for (const [name, v] of Object.entries(tokens.layout)) {
  push(`  --px-${name}: ${v};`);
}
push('}');
push('');

for (const env of ['gallery', 'vault']) {
  push(`[data-env="${env}"] {`);
  for (const [name, v] of Object.entries(tokens.env[env])) {
    push(`  --${name}: ${v};`);
  }
  push('}');
  push('');
}

push('@media (prefers-reduced-motion: reduce) {');
push('  :root {');
push('    --px-dur-surface: 0ms;');
push('    --px-dur-current: 0ms;');
push('  }');
push('}');
push('');

const out = L.join('\n');
fs.writeFileSync(path.join(here, 'css', 'variables.css'), out, 'utf8');
console.log(`[tokens] css/variables.css written (${out.length} bytes)`);
